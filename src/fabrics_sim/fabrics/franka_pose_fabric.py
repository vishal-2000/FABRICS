"""Franka Panda pose fabric.

Opens a 6-DoF end-effector pose action space on the tool centre point (``panda_tcp``,
between the fingertips) and drives the 7 arm joints toward it while respecting joint
limits, acceleration/jerk limits, self-collision and world collision (via body spheres).

The gripper is *not* part of the fabric: the finger joints are fixed at the open width in
``models/robots/urdf/franka/franka.urdf`` and the finger spheres therefore collide
conservatively. Command the gripper directly in the simulator.

Construction mirrors ``KukaAllegroPoseFabric``; assets are generated by
``tools/make_franka_fabric_assets.py``.
"""
import torch

from fabrics_sim.fabric_terms.attractor import Attractor
from fabrics_sim.fabric_terms.joint_limit_repulsion import JointLimitRepulsion
from fabrics_sim.fabric_terms.body_sphere_3d_repulsion import BodySphereRepulsion
from fabrics_sim.fabric_terms.body_sphere_3d_repulsion import BaseFabricRepulsion
from fabrics_sim.fabrics.fabric import BaseFabric
from fabrics_sim.taskmaps.identity import IdentityMap
from fabrics_sim.taskmaps.upper_joint_limit import UpperJointLimitMap
from fabrics_sim.taskmaps.lower_joint_limit import LowerJointLimitMap
from fabrics_sim.energy.euclidean_energy import EuclideanEnergy
from fabrics_sim.taskmaps.robot_frame_origins_taskmap import RobotFrameOriginsTaskMap
from fabrics_sim.utils.path_utils import get_robot_urdf_path
from fabrics_sim.utils.rotation_utils import euler_to_matrix, matrix_to_euler
from fabrics_sim.utils.rotation_utils import quaternion_to_matrix, matrix_to_quaternion


class FrankaPoseFabric(BaseFabric):
    """Fabric for the Franka Panda arm with a TCP pose action space."""

    ROBOT_DIR_NAME = "franka"
    ROBOT_NAME = "franka"
    EE_FRAME = "panda_tcp"
    # Must match AXIS_POINT_OFFSET in tools/make_franka_fabric_assets.py.
    AXIS_POINT_OFFSET = 0.25
    # Joint configuration the IsaacLab Franka tasks start from (folded, hand over the base).
    INIT_CONFIG = [0.0, -0.569, 0.0, -2.810, 0.0, 3.037, 0.741]
    # Home of the geometric posture attractor: a mid-workspace *reach* posture (elbow partly
    # extended, hand down over the table). Using INIT_CONFIG here made the wrist over-pitch into
    # its joint limit on low/forward targets (56% success); this posture gives 100%.
    DEFAULT_CONFIG = [0.0, 0.5, 0.0, -2.0, 0.0, 2.5, 0.78]

    def __init__(self, batch_size, device, timestep, graph_capturable=True,
                 fabric_params_filename="franka_pose_params.yaml", fabric_params=None):
        """
        :param fabric_params: optional dict overriding the YAML (same structure as its
                              ``fabric_params`` section); useful for tuning sweeps.
        """
        super().__init__(device, batch_size, timestep, fabric_params_filename,
                         fabric_params=fabric_params, graph_capturable=graph_capturable)

        self.urdf_path = get_robot_urdf_path(self.ROBOT_DIR_NAME, self.ROBOT_NAME)
        self.load_robot(self.ROBOT_DIR_NAME, self.ROBOT_NAME, batch_size)
        assert self._num_joints == 7, f"expected 7 revolute joints, found {self._num_joints}"

        default_config = torch.tensor(self.DEFAULT_CONFIG, device=self.device)
        self.default_config = default_config.unsqueeze(0).repeat(self.batch_size, 1)

        self.construct_fabric()

        # Target pose as (origin[3], row-major-transposed rotation[9]).
        self._ee_pose_target = torch.zeros(batch_size, 12, device=device)
        # Target expressed as the 7 attractor points.
        self._native_ee_target = None
        # Pre-allocated buffers for _pose_target_to_points. Anything created from host data
        # inside set_features would break CUDA-graph capture, so build them once here.
        a = self.AXIS_POINT_OFFSET
        self._axis_points_local = torch.tensor(
            [[0, 0, 0, 1], [a, 0, 0, 1], [-a, 0, 0, 1], [0, a, 0, 1], [0, -a, 0, 1],
             [0, 0, a, 1], [0, 0, -a, 1]], device=device, dtype=torch.float32)
        self._T = torch.zeros(batch_size, 4, 4, device=device)
        self._T[:, 3, 3] = 1.

    # ------------------------------------------------------------------ terms
    def add_joint_limit_repulsion(self):
        joints = [j for j in self.urdfpy_robot.joints if j.joint_type == 'revolute']
        upper = [j.limit.upper for j in joints]
        lower = [j.limit.lower for j in joints]

        self.add_taskmap("upper_joint_limit",
                         UpperJointLimitMap(upper, self.batch_size, self.device),
                         graph_capturable=self.graph_capturable)
        self.add_fabric("upper_joint_limit", "joint_limit_repulsion",
                        JointLimitRepulsion(True, self.fabric_params['joint_limit_repulsion'],
                                            self.device, graph_capturable=self.graph_capturable))

        self.add_taskmap("lower_joint_limit",
                         LowerJointLimitMap(lower, self.batch_size, self.device),
                         graph_capturable=self.graph_capturable)
        self.add_fabric("lower_joint_limit", "joint_limit_repulsion",
                        JointLimitRepulsion(True, self.fabric_params['joint_limit_repulsion'],
                                            self.device, graph_capturable=self.graph_capturable))

    def add_cspace_attractor(self):
        """Attractors toward the home configuration (redundancy resolution / posture bias).

        Always adds the geometric (non-forcing, energy-neutral) attractor ``cspace_attractor``.
        If the params contain ``forcing_cspace_attractor`` a forcing attractor is added too:
        it does work, biasing the posture toward home so the arm does not wander into
        twisted configurations from which the pose attractor cannot recover locally.
        """
        self.add_taskmap("identity", IdentityMap(self.device), graph_capturable=self.graph_capturable)
        self.add_fabric("identity", "cspace_attractor",
                        Attractor(False, self.fabric_params['cspace_attractor'],
                                  self.device, graph_capturable=self.graph_capturable))
        if self.fabric_params.get('forcing_cspace_attractor') is not None:
            self.add_fabric("identity", "forcing_cspace_attractor",
                            Attractor(True, self.fabric_params['forcing_cspace_attractor'],
                                      self.device, graph_capturable=self.graph_capturable))

    def add_ee_points_attractor(self):
        """Forcing attractor on 7 points rigidly attached to the TCP (origin + +-axis points)."""
        frames = [self.EE_FRAME,
                  f"{self.EE_FRAME}_x", f"{self.EE_FRAME}_x_neg",
                  f"{self.EE_FRAME}_y", f"{self.EE_FRAME}_y_neg",
                  f"{self.EE_FRAME}_z", f"{self.EE_FRAME}_z_neg"]
        self.add_taskmap("ee", RobotFrameOriginsTaskMap(self.urdf_path, frames,
                                                        self.batch_size, self.device),
                         graph_capturable=self.graph_capturable)
        self.add_fabric("ee", "ee_attractor",
                        Attractor(True, self.fabric_params['ee_attractor'],
                                  self.device, graph_capturable=self.graph_capturable))

    def add_body_repulsion(self):
        params = self.fabric_params['body_repulsion']
        frames = params['collision_sphere_frames']
        self.collision_sphere_radii = params['collision_sphere_radii']
        assert len(frames) == len(self.collision_sphere_radii)

        pairs = list(params['collision_sphere_pairs'])
        if len(pairs) == 0:
            for prefix1, prefix2 in params['collision_link_prefix_pairs']:
                for s1 in [s for s in frames if prefix1 in s]:
                    for s2 in [s for s in frames if prefix2 in s]:
                        pairs.append([s1, s2])
        collision_matrix = torch.zeros(len(frames), len(frames), dtype=int, device=self.device)
        for s1, s2 in pairs:
            collision_matrix[frames.index(s1), frames.index(s2)] = 1

        self.add_taskmap("body_points", RobotFrameOriginsTaskMap(self.urdf_path, frames,
                                                                 self.batch_size, self.device),
                         graph_capturable=self.graph_capturable)

        sphere_radius = torch.tensor(self.collision_sphere_radii, device=self.device)
        sphere_radius = sphere_radius.repeat(self.batch_size, 1)
        self.add_fabric("body_points", "repulsion",
                        BodySphereRepulsion(True, params, self.batch_size, sphere_radius,
                                            collision_matrix, self.device,
                                            graph_capturable=self.graph_capturable))
        self.add_fabric("body_points", "geom_repulsion",
                        BodySphereRepulsion(False, params, self.batch_size, sphere_radius,
                                            collision_matrix, self.device,
                                            graph_capturable=self.graph_capturable))
        self.base_fabric_repulsion = BaseFabricRepulsion(params, self.batch_size, sphere_radius,
                                                         collision_matrix, self.device)

    def add_cspace_energy(self):
        self.add_energy("identity", "euclidean",
                        EuclideanEnergy(self.batch_size, self._num_joints, self.device))

    def construct_fabric(self):
        self.add_joint_limit_repulsion()
        self.add_cspace_attractor()
        self.add_ee_points_attractor()
        self.add_body_repulsion()
        self.add_cspace_energy()

    # ---------------------------------------------------------------- targets
    def _pose_target_to_points(self):
        """(origin, R^T flattened) -> the 7 attractor points, b x 21."""
        b = self.batch_size
        T = self._T
        T[:, :3, :3] = torch.transpose(self._ee_pose_target[:, 3:].reshape(b, 3, 3), 1, 2)
        T[:, :3, 3] = self._ee_pose_target[:, :3]
        pts = torch.einsum('bij,pj->bpi', T, self._axis_points_local)[:, :, :3]   # b x 7 x 3
        return pts.reshape(b, 21)

    def get_ee_pose(self, cspace_position, orientation_convention):
        """TCP pose for joint positions ``cspace_position`` (b x 7).

        Returns b x 6 (x, y, z, euler ZYX) or b x 7 (x, y, z, qx, qy, qz, qw).
        """
        pts, _ = self.get_taskmap("ee")(cspace_position, None)
        origin = pts[:, :3]
        x_axis = torch.nn.functional.normalize(pts[:, 3:6] - origin, dim=1)
        y_axis = torch.nn.functional.normalize(pts[:, 9:12] - origin, dim=1)
        z_axis = torch.nn.functional.normalize(pts[:, 15:18] - origin, dim=1)
        R = torch.stack([x_axis, y_axis, z_axis], dim=2)   # columns are the axes

        if orientation_convention == "euler_zyx":
            orientation = matrix_to_euler(R)
        elif orientation_convention == "quaternion":
            wxyz = matrix_to_quaternion(R)
            orientation = torch.cat([wxyz[:, 1:4], wxyz[:, 0:1]], dim=1)   # -> (x,y,z,w)
        else:
            raise ValueError('orientation_convention must be "euler_zyx" or "quaternion"')
        return torch.cat([origin, orientation], dim=-1)

    def get_sphere_radii(self):
        return self.collision_sphere_radii

    @property
    def collision_status(self):
        """b bool tensor: any body sphere in collision (self or world)."""
        return self.base_fabric_repulsion.collision_status

    def set_features(self, ee_pose_target, orientation_convention,
                     batched_cspace_position, batched_cspace_velocity,
                     object_ids, object_indicator,
                     cspace_target=None, cspace_damping_gain=None):
        """Feed one control step's inputs to the fabric terms.

        :param ee_pose_target: b x 6 (x,y,z, euler ZYX) or b x 7 (x,y,z, qx,qy,qz,qw) TCP target
        :param orientation_convention: "euler_zyx" or "quaternion"
        :param batched_cspace_position: b x 7 current joint position
        :param batched_cspace_velocity: b x 7 current joint velocity
        :param object_ids, object_indicator: from WorldMeshesModel.get_object_ids()
        :param cspace_target: optional b x 7 home configuration for redundancy resolution
        """
        home = self.default_config if cspace_target is None else cspace_target
        self.fabrics_features["identity"]["cspace_attractor"] = home
        if "forcing_cspace_attractor" in self.fabrics_features["identity"]:
            self.fabrics_features["identity"]["forcing_cspace_attractor"] = home

        self._ee_pose_target[:, :3] = ee_pose_target[:, :3]
        if orientation_convention == "euler_zyx":
            assert ee_pose_target.shape[1] == 6, "euler target must be b x 6"
            R = euler_to_matrix(ee_pose_target[:, 3:])
        elif orientation_convention == "quaternion":
            assert ee_pose_target.shape[1] == 7, "quaternion target must be b x 7"
            # (x,y,z,w) -> (w,x,y,z) via slices: list indexing would upload an index tensor and
            # break CUDA-graph capture.
            wxyz = torch.cat([ee_pose_target[:, 6:7], ee_pose_target[:, 3:6]], dim=1)
            R = quaternion_to_matrix(wxyz)
        else:
            raise ValueError('orientation_convention must be "euler_zyx" or "quaternion"')
        self._ee_pose_target[:, 3:] = torch.transpose(R, 1, 2).reshape(self.batch_size, 9)

        native = self._pose_target_to_points()
        if self._native_ee_target is None:
            self._native_ee_target = torch.clone(native)
        else:
            self._native_ee_target.copy_(native)
        self.fabrics_features["ee"]["ee_attractor"] = self._native_ee_target
        self.get_fabric_term("ee", "ee_attractor").damping_position = self._native_ee_target

        body_pos, jac = self.get_taskmap("body_points")(batched_cspace_position, None)
        body_vel = torch.bmm(jac, batched_cspace_velocity.unsqueeze(2)).squeeze(2)
        self.base_fabric_repulsion.calculate_response(body_pos, body_vel, object_ids, object_indicator)
        self.fabrics_features["body_points"]["repulsion"] = self.base_fabric_repulsion
        self.fabrics_features["body_points"]["geom_repulsion"] = self.base_fabric_repulsion

        if cspace_damping_gain is not None:
            self.fabric_params['cspace_damping']['gain'] = cspace_damping_gain
